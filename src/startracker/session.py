"""First-session plan: combines the season scan, the tracking-error model and
the exposure planner into docs/session-plan.md. Everything about image quality
in it is predicted, not measured."""

from __future__ import annotations

import datetime as dt
import math
from dataclasses import dataclass

from . import errors, exposure, planner
from .optics import Camera, Lens, field_of_view_deg, plate_scale_arcsec_per_px


@dataclass(frozen=True)
class LensOption:
    label: str
    lens: Lens
    note: str = ""


LENSES = (
    LensOption("Telephoto 200 mm f/5.6", Lens(200.0, 5.6), "e.g. EF-S 55-250 at 200 mm, wide open"),
    LensOption("Telephoto 135 mm f/5.6", Lens(135.0, 5.6), "same zoom at 135 mm: easier tracking"),
    LensOption(
        "Kit zoom 55 mm f/5.6", Lens(55.0, 5.6), "EF-S 18-55 at 55 mm: M42 small, sword of Orion"
    ),
)


#: Practical cap on a first night: wind gusts, aircraft and satellites cost
#: less with shorter subs.
MAX_SUB_S = 120.0


@dataclass
class ExposureRow:
    option: LensOption
    scale: float
    fov: tuple[float, float]
    limit_expected: float
    limit_worst: float
    sub: exposure.SubPlan


def exposure_rows(
    setup: errors.Setup, sqm: float, window_s: float, max_total_s: float, max_blur_px: float
) -> list[ExposureRow]:
    rows = []
    for opt in LENSES:
        s = setup.with_(lens=opt.lens)
        exp_lim = errors.longest_sharp_exposure(s, max_blur_px, use_rss=True)
        worst = errors.longest_sharp_exposure(s, max_blur_px, use_rss=False)
        sub = exposure.plan_subs(
            min(exp_lim, MAX_SUB_S),
            sqm,
            opt.lens,
            s.camera,
            window_s=window_s,
            max_total_s=max_total_s,
        )
        rows.append(
            ExposureRow(
                opt,
                plate_scale_arcsec_per_px(s.camera, opt.lens.focal_mm),
                field_of_view_deg(s.camera, opt.lens.focal_mm),
                exp_lim,
                worst,
                sub,
            )
        )
    return rows


def _t(x: dt.datetime | None) -> str:
    return "-" if x is None else f"{x:%H:%M}"


def build_plan(
    start: dt.date,
    n_nights: int | None = None,
    not_before: dt.date | None = None,
    setup: errors.Setup | None = None,
    sqm_dark: float = 20.5,
    sqm_city: float = 18.0,
    max_blur_px: float = 1.5,
    first_session_integration_s: float = 3600.0,
    backend=None,
) -> tuple[str, planner.Season, planner.Night]:
    setup = setup or errors.Setup()
    if n_nights is None:  # through the end of March: M42 season is over by April
        end_year = start.year + 1 if start.month >= 4 else start.year
        n_nights = (dt.date(end_year, 3, 31) - start).days + 1
    season = planner.scan_season(start, n_nights, backend=backend)
    pick, backups = planner.recommend_first_session(season, 2.0, not_before)
    win = pick.best_window
    assert win is not None
    window_s = (win[1] - win[0]).total_seconds() - 30 * 60  # framing, test frames, a rewind
    rows_dark = exposure_rows(setup, sqm_dark, window_s, first_session_integration_s, max_blur_px)
    rows_city = exposure_rows(setup, sqm_city, window_s, first_session_integration_s, max_blur_px)
    cam: Camera = setup.camera
    L = []
    w = L.append
    w("# First-session plan: M42 from Lebanon")
    w("")
    w(
        f"_Generated by `startracker plan` on {dt.date.today():%Y-%m-%d}. "
        f"Ephemeris: {season.backend}. Times are local ({season.site.tz})._"
    )
    w("")
    w("> Every exposure length, blur and SNR figure here is a **prediction** from the models in")
    w("> `src/startracker/` (assumptions listed in README section 6). Nothing has been tested")
    w("> on the sky yet.")
    w("")
    c = season.criteria
    w("## Criteria")
    w("")
    w(
        f"- Site: {season.site.name} ({season.site.lat_deg:.4f} N, {season.site.lon_deg:.4f} E). "
        "A darker site inland changes these times by only minutes."
    )
    w(f"- Astronomical darkness: Sun below {c.sun_alt_max:.0f} deg.")
    w(
        f"- {season.target.name} at least {c.target_alt_min:.0f} deg up "
        f"(airmass <= {planner.airmass(c.target_alt_min):.2f})."
    )
    w(f"- Moon below the horizon, or at most {c.moon_illum_ok:.0%} illuminated.")
    w("")
    w("## Season at a glance")
    w("")
    w("| Month | Nights with >= 2 h | Usable hours | Best night | Best window |")
    w("|---|---|---|---|---|")
    for r in planner.monthly_summary(season):
        b = r["best"]
        bw = planner.fmt_window(b.best_window) if b.best_window else "-"
        w(f"| {r['month']} | {r['nights_2h']} | {r['hours']:.0f} | {b.date:%a %d %b} | {bw} |")
    w("")
    w("![M42 season](../figures/m42_season.png)")
    w("")
    w("## Recommended first session")
    w("")
    nb = (
        f" (on or after {not_before:%d %b %Y}, leaving time to build and bench-test)"
        if not_before
        else ""
    )
    w(f"**{pick.date:%A %d %B %Y}**, night into {pick.date + dt.timedelta(days=1):%A}{nb}.")
    w("")
    w(
        f"- Astronomical darkness {_t(pick.dark_start)}-{_t(pick.dark_end)}; "
        f"usable M42 window **{planner.fmt_window(win)}** ({planner.hours_to_hm(pick.usable_h)})."
    )
    w(
        f"- M42 transits at {_t(pick.transit_local)}, reaching {pick.target_max_alt:.0f} deg "
        f"in darkness. Moon at midnight: {planner.moon_phase_name(pick.moon_illum)}."
    )
    w(
        "- Backups: "
        + "; ".join(
            f"{n.date:%a %d %b} {planner.fmt_window(n.best_window)} "
            f"({planner.hours_to_hm(n.usable_h)})"
            for n in backups
            if n.best_window
        )
    )
    w("")
    w("![First night](../figures/m42_first_night.png)")
    w("")
    w("### Timeline")
    w("")
    t0 = win[0]
    steps = [
        (
            -90,
            "Arrive, set up the tripod on firm ground, level it roughly, power on, "
            "connect to the StarTracker Wi-Fi (the page sends the phone's clock).",
        ),
        (
            -75,
            "Home the tracker. Polar-align with the sight tube: Polaris on the reticle "
            "ring at the clock position the web page shows. Lock the tripod head.",
        ),
        (
            -50,
            "Mount the camera. Manual mode, RAW, IS off, AF off, long-exposure noise "
            "reduction off, live view x10 on a bright star; focus with the Bahtinov mask.",
        ),
        (
            -30,
            "Frame M42 (below Orion's belt). Test frames: 5 s at ISO 1600 to frame, then one "
            "full-length sub - check stars at 100 %, histogram peak in the left third.",
        ),
        (-10, "Rewind to the start of travel so the first run gets the full ~2.3 h."),
        (0, "Start tracking (sidereal) and the BULB sequence from the web page."),
        (
            140,
            "Before end of travel (the page shows time left): stop, rewind (~40 s), "
            "re-frame, restart.",
        ),
    ]
    for dmin, text in steps:
        tt = t0 + dt.timedelta(minutes=dmin)
        sign = "T" if dmin == 0 else f"T{dmin:+d} min"
        w(f"- **{tt:%H:%M}** ({sign}): {text}")
    w(f"- **{win[1]:%H:%M}**: window ends. Shoot calibration frames (below) before packing up.")
    w("")
    w("### Exposure settings (predicted)")
    w("")
    w(
        f"Camera: {cam.name}, {cam.pixel_um:.2f} um pixels. Tracking limits are the longest sub "
        f"whose predicted trail stays <= {max_blur_px} px with {setup.polar_error_deg} deg polar "
        "error (sight tube), lead-screw PE +-4 um (assumed) and no PEC. 'Expected' adds the "
        "independent errors in quadrature; 'worst' adds them linearly. Subs are capped at "
        f"{MAX_SUB_S:.0f} s and the first night's integration at 60 min."
    )
    w("")
    for label, sqm, rows in (
        ("Dark site", sqm_dark, rows_dark),
        ("Beirut city", sqm_city, rows_city),
    ):
        w(f"**{label}** (assumed sky {sqm} mag/arcsec^2):")
        w("")
        w("| Lens | Scale | Field | Sharp sub, expected / worst | ISO | Sub | Subs | Integration |")
        w("|---|---|---|---|---|---|---|---|")
        for r in rows:
            mark = " (a)" if r.sub.read_noise_limited else ""
            w(
                f'| {r.option.label} | {r.scale:.1f}"/px | {r.fov[0]:.1f} x {r.fov[1]:.1f} deg | '
                f"{r.limit_expected:.0f} s / {r.limit_worst:.0f} s | {r.sub.iso} | "
                f"{r.sub.sub_s:.0f} s{mark} | {r.sub.n_subs} | {r.sub.total_s / 60:.0f} min |"
            )
        w("")
        if any(r.sub.read_noise_limited for r in rows):
            w(
                "(a) Read-noise limited: the sub is too short for this dark a sky to bury the read "
                "noise (sky noise < sqrt(5) x read noise). Fine for M42, which is bright; stack "
                "more subs."
            )
            w("")
    prim = rows_dark[0]
    w(
        f"**Plan for the night:** {prim.option.label} ({prim.option.note}), ISO {prim.sub.iso}, "
        f"**{prim.sub.n_subs} x {prim.sub.sub_s:.0f} s** BULB subs, 3 s gap "
        f"(about {prim.sub.total_s / 60:.0f} min of integration). If the test frame shows "
        "trailing, drop to 135 mm or halve the sub length - many short subs stack fine on a "
        "target as bright as M42."
    )
    w("")
    w(
        "The Trapezium core saturates in long subs. Add **20 x 3 s** subs at the same ISO for an "
        "HDR blend of the core (optional for a first photograph)."
    )
    w("")
    neb = exposure.SensorNoise()
    s_faint = exposure.surface_rate_e_s(21.5, prim.option.lens, cam, neb)
    s_bright = exposure.surface_rate_e_s(18.0, prim.option.lens, cam, neb)
    snr = {}
    for label, rows in (("dark", rows_dark), ("city", rows_city)):
        r = rows[0]
        rn = neb.rn(r.sub.iso)
        for name, sig in (("faint", s_faint), ("bright", s_bright)):
            snr[(label, name)] = exposure.stack_snr(
                sig, r.sub.sky_e_s, r.sub.sub_s, r.sub.n_subs, rn, neb.dark_e_s
            )
    w(
        f"Predicted per-pixel SNR of the stack (rough photometry, +-50 %): outer nebulosity "
        f"(~21.5 mag/arcsec^2) {snr[('dark', 'faint')]:.0f} at the dark site vs "
        f"{snr[('city', 'faint')]:.0f} in Beirut; bright Huygens region (~18) "
        f"{snr[('dark', 'bright')]:.0f} vs {snr[('city', 'bright')]:.0f}. The city sky still gives "
        "a clear M42; the dark site gives the outer wings."
    )
    w("")
    w("### Calibration frames")
    w("")
    w(
        f"- **Darks:** 20 x {prim.sub.sub_s:.0f} s, same ISO, lens cap on, at the end of the "
        "session (same temperature)."
    )
    w(
        "- **Flats:** 30 at the same focus and aperture: white T-shirt over the lens, pointed at "
        "the dawn sky or a tablet showing white; Av mode."
    )
    w("- **Bias:** 50 at the fastest shutter speed, cap on, same ISO.")
    w("")
    w("### Processing (free software)")
    w("")
    w(
        "Siril (Linux/Windows/macOS) or DeepSkyStacker (Windows): calibrate, register, stack with "
        "sigma clipping; reject frames with high FWHM/roundness. Then background extraction, "
        "colour calibration, a gentle stretch. Stars should be round at 100 % - the measurable "
        "test of this tracker."
    )
    w("")
    w("## Why these numbers")
    w("")
    T = prim.sub.sub_s
    b = errors.blur_budget(setup.with_(lens=prim.option.lens), T)
    w(
        f"Predicted trail budget for one {T:.0f} s sub at {prim.option.lens.focal_mm:.0f} mm "
        f'({prim.scale:.2f}"/px), worst point of the travel:'
    )
    w("")
    w("| Source | Trail (arcsec) | Pixels |")
    w("|---|---|---|")
    for k, v in b.terms.items():
        w(f"| {k} | {v:.2f} | {v / b.scale_arcsec_px:.2f} |")
    w(f"| **sum (worst)** | **{b.total:.2f}** | **{b.total_px:.2f}** |")
    w(f"| **RSS (expected)** | **{b.rss:.2f}** | **{b.rss / b.scale_arcsec_px:.2f}** |")
    w("")
    untr = errors.untracked_limit(setup.with_(lens=prim.option.lens), max_blur_px)
    r500 = float(exposure.rule_500(prim.option.lens.focal_mm, cam.crop_factor))
    npf = float(
        exposure.npf_simple(prim.option.lens.focal_mm, prim.option.lens.f_number, cam.pixel_um)
    )
    w(
        f"Untracked at the same focal length: {untr:.2f} s for the same {max_blur_px} px "
        f"criterion (500 rule: {r500:.1f} s; NPF: {npf:.1f} s). Tracking buys a factor of "
        f"~{prim.limit_expected / untr:.0f} in sub length."
    )
    w("")
    return "\n".join(L) + "\n", season, pick


def predicted_headline(setup: errors.Setup | None = None, max_blur_px: float = 1.5) -> dict:
    """A handful of predicted numbers for the README / portfolio."""
    setup = setup or errors.Setup()
    out = {}
    for f in (50.0, 135.0, 200.0):
        s = setup.with_(lens=Lens(f, 5.6))
        out[f] = {
            "expected": errors.longest_sharp_exposure(s, max_blur_px, use_rss=True),
            "worst": errors.longest_sharp_exposure(s, max_blur_px),
            "untracked": errors.untracked_limit(s, max_blur_px),
        }
    pec = setup.with_(mech=setup.mech.with_(pec_residual=0.25), lens=Lens(200.0, 5.6))
    out["200_pec"] = errors.longest_sharp_exposure(pec, max_blur_px, use_rss=True)
    out["tracking_h"] = setup.geom.tracking_duration_s() / 3600.0
    out["pa_typical_factor"] = errors.pa_blur_typical_factor(setup.dec_deg)
    out["one_microstep_arcsec"] = (
        math.degrees(float(setup.geom.rad_per_microstep(setup.geom.home_angle))) * 3600
    )
    return out
